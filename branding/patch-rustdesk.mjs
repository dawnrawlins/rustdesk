#!/usr/bin/env node
// Bakes a company's server settings into a RustDesk source checkout.
//
//   node patch-rustdesk.mjs --rustdesk-dir ../rustdesk \
//     --host rd.example.com --key <hbbs public key> \
//     --api-base https://example.com --token <company enroll token> \
//     [--relay rd.example.com:21117] [--variant client|agent] [--app-name "Acme Support"] [--group "Acme"]
//     [--site https://example.com] [--brand-file branding/brand.json]
//
// The patch is a marked block at the top of `load_custom_client()` in src/common.rs, which
// both the Sciter and Flutter builds call at start-up. Re-running replaces the block.
// It also writes branding/brand.json (so the build workflow can re-apply the same brand with
// --brand-file) and de-brands the sources: every rustdesk.com server/key/URL is replaced by
// the company's own, so the binary never talks to the public infrastructure.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { builtinSettings, hardSettings, overwriteLocalSettings, overwriteSettings, parseArgs, resolveBrand } from "./lib/branding.mjs";

const BEGIN = "    // RD-BRANDING:BEGIN (generated by rustdesk/client-build/patch-rustdesk.mjs)";
const END = "    // RD-BRANDING:END";

function rustStr(s) {
  let out = '"';
  for (const ch of String(s)) {
    const cp = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (cp < 0x20 || cp > 0x7e) out += `\\u{${cp.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

function block(brand) {
  const lines = [BEGIN, "    {"];
  const map = (name, entries) => {
    if (!Object.keys(entries).length) return;
    lines.push(`        let mut s = config::${name}.write().unwrap();`);
    for (const [k, v] of Object.entries(entries)) lines.push(`        s.insert(${rustStr(k)}.to_owned(), ${rustStr(v)}.to_owned());`);
    lines.push("        drop(s);");
  };
  map("OVERWRITE_SETTINGS", overwriteSettings(brand));
  map("OVERWRITE_LOCAL_SETTINGS", overwriteLocalSettings(brand));
  map("BUILTIN_SETTINGS", builtinSettings(brand));
  map("HARD_SETTINGS", hardSettings(brand));
  if (brand.appName) lines.push(`        *config::APP_NAME.write().unwrap() = ${rustStr(brand.appName)}.to_owned();`);
  lines.push("    }", END);
  return lines.join("\n");
}

export function patchCommonRs(src, brand) {
  const stripped = src.replace(new RegExp(`\\n${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`), "");
  const anchor = /pub fn load_custom_client\(\)\s*\{/;
  if (!anchor.test(stripped)) {
    throw new Error("Could not find `pub fn load_custom_client() {` in src/common.rs - RustDesk layout changed, update the patch anchor.");
  }
  for (const name of ["OVERWRITE_SETTINGS", "OVERWRITE_LOCAL_SETTINGS"]) {
    if (!new RegExp(`config::${name}`).test(stripped)) {
      throw new Error(`src/common.rs no longer references config::${name} - verify the hbb_common API before patching.`);
    }
  }
  return stripped.replace(anchor, (m) => `${m}\n${block(brand)}`);
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// ---------------------------------------------------------------------------------------------
// De-branding: point every compiled-in rustdesk.com server, key and link at the company's own.

const hostOnly = (host) => host.split(":")[0];

function readSource(dir, rel) {
  const file = path.join(dir, ...rel.split("/"));
  if (!fs.existsSync(file)) {
    throw new Error(`${rel} not found${rel.startsWith("libs/hbb_common/") ? " - run `git submodule update --init --recursive` first" : ""}`);
  }
  return [file, fs.readFileSync(file, "utf8")];
}

/** Replaces `re` in `src`. Throws when nothing matched unless the file already holds the brand value. */
function replaceOrFail(rel, src, re, replacement, alreadyBranded) {
  let n = 0;
  const out = src.replace(re, (...m) => {
    n++;
    return typeof replacement === "function" ? replacement(...m) : replacement;
  });
  if (n === 0 && !alreadyBranded(src)) {
    throw new Error(`${rel}: pattern ${re} not found - RustDesk layout changed, update debrand() in branding/patch-rustdesk.mjs`);
  }
  return [out, n];
}

/** Character ranges of `#[cfg(test)]` items (the attribute up to the end of the following item). */
function testRanges(src) {
  const ranges = [];
  const attr = /#\[cfg\(test\)\]/g;
  let m;
  while ((m = attr.exec(src))) {
    const start = m.index;
    let i = m.index + m[0].length;
    while (i < src.length && src[i] !== "{" && src[i] !== ";") i++;
    if (src[i] === "{") {
      let depth = 0;
      for (; i < src.length; i++) {
        if (src[i] === "{") depth++;
        else if (src[i] === "}" && --depth === 0) break;
      }
    }
    ranges.push([start, i]);
    attr.lastIndex = Math.max(attr.lastIndex, i);
  }
  return ranges;
}

const PUBLIC_URL = /https?:\/\/(www\.)?rustdesk\.com[^"'\s]*|https?:\/\/github\.com\/rustdesk\/rustdesk\/releases[^"'\s]*/g;

/** Rewrites public URL string literals outside comments, `is_public()` and `#[cfg(test)]` code. Returns [out, count]. */
function replacePublicUrls(src, site) {
  const ranges = testRanges(src);
  const lines = src.split("\n");
  let offset = 0;
  let n = 0;
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li];
    const start = offset;
    offset += line.length + 1;
    const trimmed = line.trimStart();
    if (trimmed.startsWith("//") || trimmed.startsWith("*") || trimmed.startsWith("/*")) continue;
    if (line.includes("is_public(")) continue;
    if (ranges.some(([a, b]) => start >= a && start <= b)) continue;
    // Only the code part of the line: a trailing `// ...` comment starts at the first `//` not preceded by `:`.
    const cm = /(?<!:)\/\//.exec(line);
    const code = cm ? line.slice(0, cm.index) : line;
    const comment = cm ? line.slice(cm.index) : "";
    const replaced = code.replace(PUBLIC_URL, () => {
      n++;
      return site;
    });
    lines[li] = replaced + comment;
  }
  return [lines.join("\n"), n];
}

function walk(dir, exts, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, out);
    else if (exts.some((x) => e.name.endsWith(x))) out.push(p);
  }
  return out;
}

export function debrand(dir, brand) {
  const host = hostOnly(brand.host);
  const site = brand.site;
  const summary = [];
  const write = (file, before, after, rel, n) => {
    if (after !== before) fs.writeFileSync(file, after);
    summary.push(`  ${rel}: ${n}`);
  };

  // a. hbb_common config: default ID server, its public key, docs links.
  {
    const rel = "libs/hbb_common/src/config.rs";
    const [file, before] = readSource(dir, rel);
    let src = before;
    let total = 0;
    let n;
    [src, n] = replaceOrFail(rel, src, /pub const RENDEZVOUS_SERVERS: &\[&str\] = &\[[^\]]*\];/, `pub const RENDEZVOUS_SERVERS: &[&str] = &[${rustStr(host)}];`, (s) => s.includes(`&[${rustStr(host)}]`));
    total += n;
    [src, n] = replaceOrFail(rel, src, /pub const RS_PUB_KEY: &str = "[^"]*";/, `pub const RS_PUB_KEY: &str = ${rustStr(brand.key)};`, (s) => s.includes(`RS_PUB_KEY: &str = ${rustStr(brand.key)}`));
    total += n;
    for (const name of ["LINK_DOCS_HOME", "LINK_DOCS_X11_REQUIRED"]) {
      [src, n] = replaceOrFail(rel, src, new RegExp(`pub const ${name}: &str = "[^"]*";`), `pub const ${name}: &str = ${rustStr(site)};`, (s) => s.includes(`${name}: &str = ${rustStr(site)}`));
      total += n;
    }
    write(file, before, src, rel, total);
  }

  // b. version check endpoint.
  {
    const rel = "libs/hbb_common/src/lib.rs";
    const [file, before] = readSource(dir, rel);
    const target = rustStr(`${site}/version/latest`);
    const [src, n] = replaceOrFail(rel, before, /"https:\/\/api\.rustdesk\.com\/version\/latest"/g, target, (s) => s.includes(target));
    write(file, before, src, rel, n);
  }

  // c. public STUN servers -> the company's own host (array length unchanged).
  {
    const rel = "libs/hbb_common/src/webrtc.rs";
    const [file, before] = readSource(dir, rel);
    const stun = rustStr(`stun:${host}:3478`);
    const [src, n] = replaceOrFail(
      rel,
      before,
      /(static DEFAULT_ICE_SERVERS: \[&str; (\d+)\] = \[)([\s\S]*?)(\];)/,
      (_m, open, count, body, close) => {
        const literals = body.match(/"[^"]*"/g) ?? [];
        if (literals.length !== Number(count)) throw new Error(`${rel}: DEFAULT_ICE_SERVERS declares ${count} entries but ${literals.length} string literals were found`);
        return `${open}${body.replace(/"[^"]*"/g, stun)}${close}`;
      },
      () => false,
    );
    write(file, before, src, rel, n);
  }

  // d. API server fallback when no custom server is configured.
  {
    const rel = "src/common.rs";
    const [file, before] = readSource(dir, rel);
    const ranges = testRanges(before);
    const api = rustStr(brand.api);
    let n = 0;
    const src = before.replace(/"https:\/\/admin\.rustdesk\.com"/g, (m, idx) => {
      if (ranges.some(([a, b]) => idx >= a && idx <= b)) return m;
      n++;
      return api;
    });
    if (n === 0 && !before.includes(api)) throw new Error(`${rel}: "https://admin.rustdesk.com" not found outside tests - RustDesk layout changed, update debrand()`);
    write(file, before, src, rel, n);
  }

  // e. every other rustdesk.com / GitHub-release link in app code -> the company site.
  {
    const files = [...walk(path.join(dir, "src"), [".rs"]), ...walk(path.join(dir, "flutter", "lib"), [".dart"])];
    for (const file of files) {
      const rel = path.relative(dir, file).split(path.sep).join("/");
      if (/_tests\.rs$/.test(rel)) continue; // test-only module files (included under #[cfg(test)])
      const before = fs.readFileSync(file, "utf8");
      if (!PUBLIC_URL.test(before)) continue;
      PUBLIC_URL.lastIndex = 0;
      const [src, n] = replacePublicUrls(before, site);
      if (n) write(file, before, src, rel, n);
    }
  }

  // f. Deep-link URL scheme. Windows registers it at install time from the app name
  //    (src/platform/windows.rs), but macOS and Android bake it in at build time. Keep all
  //    three in sync with get_uri_scheme() in src/common.rs: lower-case, spaces removed.
  if (brand.appName) {
    const scheme = brand.appName.toLowerCase().replace(/ /g, "");
    {
      const rel = "flutter/macos/Runner/Info.plist";
      const [file, before] = readSource(dir, rel);
      const [src, n] = replaceOrFail(
        rel,
        before,
        /(<key>CFBundleURLSchemes<\/key>\s*<array>\s*<string>)rustdesk(<\/string>)/,
        (_m, open, close) => `${open}${scheme}${close}`,
        (s) => s.includes(`<string>${scheme}</string>`),
      );
      write(file, before, src, rel, n);
    }
    // The Android launcher label, the input (accessibility) service label and the strings the
    // system shows in its permission dialogs are literal "RustDesk" in the manifest/resources.
    const xmlName = brand.appName.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
    {
      const rel = "flutter/android/app/src/main/AndroidManifest.xml";
      const [file, before] = readSource(dir, rel);
      let [src, n] = replaceOrFail(rel, before, /android:scheme="rustdesk"/, `android:scheme="${scheme}"`, (s) => s.includes(`android:scheme="${scheme}"`));
      const [src2, n2] = replaceOrFail(rel, src, /android:label="RustDesk( Input)?"/g, (_m, input) => `android:label="${xmlName}${input ?? ""}"`, (s) => s.includes(`android:label="${xmlName}"`));
      write(file, before, src2, rel, n + n2);
    }
    {
      const rel = "flutter/android/app/src/main/res/values/strings.xml";
      const [file, before] = readSource(dir, rel);
      const [src, n] = replaceOrFail(rel, before, /RustDesk/g, xmlName, (s) => s.includes(`<string name="app_name">${xmlName}</string>`));
      write(file, before, src, rel, n);
    }
  }
  return summary;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log(fs.readFileSync(new URL(import.meta.url), "utf8").split("\nimport")[0]);
    return;
  }
  const brand = resolveBrand(args);
  const dir = path.resolve(args["rustdesk-dir"] ?? process.env.RUSTDESK_DIR ?? ".");
  const file = path.join(dir, "src", "common.rs");
  if (!fs.existsSync(file)) throw new Error(`${file} not found - pass --rustdesk-dir pointing at a rustdesk checkout`);
  const before = fs.readFileSync(file, "utf8");
  const after = patchCommonRs(before, brand);
  if (args["dry-run"] === "true") {
    console.log(block(brand));
    return;
  }
  fs.writeFileSync(file, after);
  // Read by the Windows packaging step so the program ships as <AppName>.exe (see flutter-build.yml).
  const appNameFile = path.join(dir, "branding", "APP_NAME");
  if (brand.appName) {
    fs.mkdirSync(path.dirname(appNameFile), { recursive: true });
    fs.writeFileSync(appNameFile, `${brand.appName.replace(/[\\/:*?"<>|]+/g, "").trim()}\n`);
  } else if (fs.existsSync(appNameFile)) {
    fs.unlinkSync(appNameFile);
  }
  // Read by the build workflow ("Apply branding" step) to re-apply the same brand after checkout.
  const brandFile = path.join(dir, "branding", "brand.json");
  fs.mkdirSync(path.dirname(brandFile), { recursive: true });
  const { host, relay, key, api, variant, appName, group, site } = brand;
  fs.writeFileSync(brandFile, `${JSON.stringify({ host, relay, key, api, variant, appName, group, site }, null, 2)}\n`);
  const summary = debrand(dir, brand);
  console.log(`Patched ${path.relative(process.cwd(), file)} (${brand.variant} build)`);
  console.log(`  id server : ${brand.host}\n  relay     : ${brand.relay}\n  api server: ${brand.api}\n  site      : ${brand.site}`);
  if (brand.appName) console.log(`  app name  : ${brand.appName}`);
  console.log(`De-branded (replacements per file):\n${summary.join("\n")}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    main();
  } catch (e) {
    console.error(`error: ${e.message}`);
    process.exit(1);
  }
}
